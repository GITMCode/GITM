#!/usr/bin/env python
"""Generate per-output-type variable tables (markdown) from netcdf output.

Point it at a directory containing one or more .nc files per output type
(e.g. a full-sweep run's UA/data) and it prints a markdown section per type
listing each variable's GITM name, units, and long_name, taken from the
files themselves, so the docs cannot drift from the code.

Usage:
    python generate_output_docs.py <dir-with-nc-files> [> variable_lists.md]

One file per type is read (the first alphabetically). Requires xarray.
"""

import glob
import os
import re
import sys

import xarray as xr

# 1-D coordinate variables. Magnetic grids name theirs mlon/mlat (see
# nc_coord_names in src/ModOutputNetCDF.F90) -- keep this in step with that
# function. Dimension coordinates normally land in ds.coords rather than
# ds.data_vars, so this is a backstop, not the only thing keeping them out.
SKIP_VARS = {"time", "lon", "lat", "z", "mlon", "mlat"}


def type_of(path):
    """Output type code from a filename like 3DALL_t021221_000000.nc."""
    m = re.match(r"([0-3]D[A-Z]{3})", os.path.basename(path))
    return m.group(1) if m else None


def main(root):
    files = {}
    for f in sorted(glob.glob(os.path.join(root, "**", "*.nc"), recursive=True)):
        t = type_of(f)
        if t and t not in files:
            files[t] = f
    if not files:
        sys.exit(f"no .nc files matching an output-type prefix under {root}")

    for t in sorted(files):
        ds = xr.open_dataset(files[t], decode_cf=False)
        print(f"### {t}\n")
        print("| Variable | Units | Description |")
        print("|---|---|---|")
        for name in ds.data_vars:
            if name in SKIP_VARS:
                continue
            a = ds[name].attrs
            gitm_name = a.get("gitm_name", name)
            units = a.get("units", "")
            long_name = a.get("long_name", "")
            print(f"| {gitm_name} | {units} | {long_name} |")
        print()
        ds.close()
    types = ", ".join(sorted(files))
    print(f"<!-- generated by srcPython/generate_output_docs.py; types: {types} -->")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
